/**
 * Return absolute trading-day distance from `entryDate` to nearest event in
 * `events`, where distance is counted via the supplied `tradingDays` array.
 * Treats events outside the trading-day grid by snapping to the nearest grid
 * date (so weekend/holiday FOMC scheduling decisions don't break the metric).
 */
export function daysToNearestEvent(
  entryDate: string,
  events: string[],
  tradingDays: string[],
): number {
  const entryIdx = tradingDays.indexOf(entryDate);
  if (entryIdx < 0) return Number.POSITIVE_INFINITY;
  let best = Number.POSITIVE_INFINITY;
  for (const ev of events) {
    let evIdx = tradingDays.indexOf(ev);
    if (evIdx < 0) {
      // Snap to nearest trading day on or after the event date.
      evIdx = tradingDays.findIndex(d => d >= ev);
      if (evIdx < 0) continue;
    }
    const d = Math.abs(evIdx - entryIdx);
    if (d < best) best = d;
  }
  return best;
}
